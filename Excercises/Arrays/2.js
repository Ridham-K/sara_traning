// Add and remove elements using:
    // push
    // pop
    // shift
    // unshift




// pushed berries
let fruits = ["apple","banana","Kiwi","Orange"];
console.log(fruits);
fruits.push("Berries")
console.log(fruits);

//pop
fruits.pop();
console.log(fruits);

//shift
fruits.shift();
console.log(fruits);

//unshift
fruits.unshift("Red");
console.log(fruits);

