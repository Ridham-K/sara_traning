// 2. Compare two numbers using comparison operators.

let num1 = 40;
let num2 = 35;
let abc = "abc"

console.log("Equal to: ", num1 == num2);
console.log("Strict Equal to(numbers): ", num1 === num2);
console.log("Strict Equal to(numbers&string): ", num1 === abc);
console.log("Not Equal to: ", num1 != num2);
console.log("Strict Not Equal to: ", num1 !== num2);
console.log("Greater than: ", num1 > num2);
console.log("Greater than equal to: ", num1 >= num2);
console.log("Less than: ", num1 < num2);
console.log("Less than equal to: ", num1 <= num2);







